@pbix_bp.get("/api/iit-quarterly")
def pbix_api_iit():
    """PBIX `Total IIT`, `%IIT`, `%IIT_Quarterly`, `IIT_Duration_Total`.

    All four are SUMs of the single element `C&T (facility) - Tx_ML, Outcomes`
    sliced by the `Outcomes` dimension, NOT separate data elements.
    """
    county = request.args.get("county", "Meru County").strip()
    subcounty = request.args.get("subcounty", "").strip() or None
    facility = request.args.get("facility", "").strip() or None
    pe = request.args.get("period", "LAST_12_MONTHS").strip()
    ou_id, _ = _resolve_ou_safe(county, subcounty, facility)
    errors: list = []

    # 1) The outcome element with its full COC breakdown (one call).
    rows = _fetch_de_coc_rows([TX_ML_OUTCOME_ELEMENT], ou_id, pe)
    names = _coc_names_for([TX_ML_OUTCOME_ELEMENT])

    # The PBIX `Outcomes` dimension is only a *prefix* of the DHIS2 COC name —
    # every COC on this element reads "<Outcome>, <Sex>, <Age band>", and this
    # DHIS2 build is not even consistent about the capital "In" on the 6+ arm.
    # Match on the outcome prefix, then classify by duration marker.
    TXML_NAMES = ("Died", "Refused (Stopped) Treatment", "Transferred Out")

    iit = {}       # period -> {"lt3","m35","m6p","total","txml"}
    for de, per, coc, val in rows:
        nm = names.get(coc, "")
        bucket = iit.setdefault(per, {"lt3": 0.0, "m35": 0.0, "m6p": 0.0,
                                      "total": 0.0, "txml": 0.0})
        if IIT_OUTCOME_PREFIX in nm[:32]:
            if IIT_LT3_MARKER in nm:
                bucket["lt3"] += val
            elif IIT_GT3_MARKERS[0] in nm:
                bucket["m35"] += val
            elif IIT_GT3_MARKERS[1] in nm:
                bucket["m6p"] += val
            else:
                continue
            bucket["total"] += val
            bucket["txml"] += val
        elif nm.startswith(TXML_NAMES):
            bucket["txml"] += val

    # 2) The %IIT denominator parts.
    #
    # 🔥 `%IIT`'s denominator reaches BACKWARD past the selected period
    # (`PREVIOUSQUARTER` for the TX_CURR baseline, plus the 3 months of the
    # calendar quarter for the TX_NEW cohort).  Fetching only `pe` therefore
    # leaves both parts empty whenever a single month is asked for, so the
    # window is widened for the denominator fetch while `trend` stays limited
    # to the months the caller actually requested.
    _lo, _hi = _pe_bounds(pe)
    results, errs = _fetch_multi([
        ("tx_curr", TX_CURR_BASELINE),
        ("tx_new_start", TX_NEW_STARTING_ART),
    ], ou_id, _widen_pe(pe))
    errors.extend(errs)

    # 🔥 The two dict families above are keyed differently — the COC rows come
    # back through `_pe_label` (display names) while the calendar helpers below
    # only ever emit 6-char codes.  Always read through `_pick`.
    def _curr(period):
        return _pick(results.get("tx_curr"), period) if period else 0.0

    def _cohort(months):
        return sum(_pick(results.get("tx_new_start"), m) for m in months)

    # 🔥 `iit` is keyed by the DHIS2 *display* name ("June 2026") because the
    # COC rows arrive through `_pe_label`, whereas `q["last"]` below is a
    # 6-char code.  Reading `iit[code]` therefore always missed and every
    # quarterly `total_iit_last_month` / duration came back 0.
    _EMPTY_IIT = {"lt3": 0.0, "m35": 0.0, "m6p": 0.0, "total": 0.0, "txml": 0.0}

    def _iit_at(period):
        if not period:
            return dict(_EMPTY_IIT)
        return (iit.get(period)
                or iit.get(_pe_name(period))
                or iit.get(_pe_code(period))
                or dict(_EMPTY_IIT))

    all_periods = sorted(
        set(iit) | {p for p in results.get("tx_curr", {})
                    if _in_pe_window(p, _lo, _hi)},
        key=_period_sort_key,
    )

    trend = []
    for p in all_periods:
        b = _iit_at(p)
        base_p = _prior_quarter_end_period(p)
        base_curr = _curr(base_p)
        cohort = _cohort(_quarter_months_to_date(p))
        denom = base_curr + cohort
        trend.append({
            "period": p,
            "label": _period_label(p),
            "total_iit": round(b["total"], 1),
            "iit_lt3": round(b["lt3"], 1),
            "iit_3to5": round(b["m35"], 1),
            "iit_6plus": round(b["m6p"], 1),
            "tx_ml": round(b["txml"], 1),
            "tx_curr_baseline": round(base_curr, 1),
            "tx_curr_baseline_period": base_p,
            "tx_new_cohort": round(cohort, 1),
            "iit_denominator": round(denom, 1),
            "iit_pct": round((b["total"] / denom * 100) if denom > 0 else 0, 1),
        })

    # 3) `%IIT_Quarterly` + `IIT_Duration_Total` — one row per calendar quarter.
    quarters: dict = {}
    for p in all_periods:
        qm = _quarter_months(p)
        if not qm:
            continue
        qkey = qm[2]
        q = quarters.setdefault(qkey, {"months": qm, "last": qm[2]})
        q["end"] = p
    quarterly = []
    for qkey in sorted(quarters, key=_period_sort_key):
        q = quarters[qkey]
        last = q["last"]
        b = _iit_at(last)
        base_p = _prior_quarter_end_period(last)
        base_curr = _curr(base_p)
        cohort = _cohort(q["months"])
        denom = base_curr + cohort
        quarterly.append({
            "quarter_end": last,
            "label": _period_label(last),
            "months": q["months"],
            "total_iit_last_month": round(b["total"], 1),
            "duration_lt3": round(b["lt3"], 1),
            "duration_3to5": round(b["m35"], 1),
            "duration_6plus": round(b["m6p"], 1),
            "tx_curr_baseline": round(base_curr, 1),
            "tx_curr_baseline_period": base_p,
            "tx_new_cohort": round(cohort, 1),
            "iit_denominator": round(denom, 1),
            "iit_pct": round((b["total"] / denom * 100) if denom > 0 else 0, 1),
        })

    return jsonify({
        "page": "IIT Quarterly",
        "county": county,
        "source": "dhis2_live",
        "period_range": pe,
        "trend": trend,
        "quarterly": quarterly,
        "measures": {
            "total_iit": "PBIX Total IIT = 'C&T (facility) - Tx_ML, Outcomes' @ the "
                         "3 Interruption outcomes",
            "iit_pct": "PBIX %IIT = DIVIDE(Total IIT, TX_CURR@prior-quarter-end + "
                       "TX_NEW: Starting ART over the quarter to date)",
            "iit_pct_quarterly": "PBIX %IIT_Quarterly = DIVIDE(Total IIT @ last "
                                 "month of quarter, TX_CURR@month before quarter "
                                 "+ TX_NEW: Starting ART for all 3 quarter months)",
            "duration": "PBIX IIT_Duration_Total = the 3 Interruption outcome "
                        "sums over the quarter months",
        },
        "fetched_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "errors": errors or None,
    })


