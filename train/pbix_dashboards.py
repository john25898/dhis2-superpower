def _fetch_multi(specs, ou_id, pe="LAST_12_MONTHS"):
    """Fetch multiple DX groups in parallel.

    specs: list of ``(key, dx_ids_or_list)``, ``(key, dx_ids_or_list, coc_ids)``
           or ``(key, callable)``.
           When ``coc_ids`` is given the element(s) are restricted to those
           category option combos (DHIS2 ``co:`` dimension) and the rows are
           summed back into a plain ``{period: value}`` mapping.
           When ``dx`` is callable it is invoked as ``dx(ou_id, pe)`` and must
           return ``{period: value}`` — used for measures that need more than
           one fetch mechanism (see ``_hts_positive_periods``).
    Returns ``({key: {period: value}}, errors)``
    """
    results = {}
    errors = []
    with ThreadPoolExecutor(max_workers=8) as ex:
        future_map = {}
        for spec in specs:
            key, dx = spec[0], spec[1]
            cocs = spec[2] if len(spec) > 2 else None
            if callable(dx):
                fut = ex.submit(dx, ou_id, pe)
            else:
                fut = ex.submit(_dhis2_fetch_safe, dx, ou_id, pe, cocs)
            future_map[fut] = (key, bool(cocs))
        for fut in as_completed(future_map):
            key, has_cocs = future_map[fut]
            try:
                raw = fut.result()
            except Exception as exc:
                errors.append(f"{key}: {exc}")
                results[key] = {}
                continue
            if not has_cocs:
                results[key] = raw or {}
                continue
            # COC-split rows come back as {(period, coc_id): value} -> collapse.
            summed = {}
            for k, v in (raw or {}).items():
                per = k[0] if isinstance(k, tuple) else k
                summed[per] = summed.get(per, 0) + float(v or 0)
            results[key] = summed
    return results, errors


