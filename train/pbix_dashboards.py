    facility = request.args.get("facility", "").strip() or None
    pe = request.args.get("period", "LAST_12_MONTHS").strip()
    ou_id, _ = _resolve_ou_safe(county, subcounty, facility)

    # 1) Trend data (existing)
    results, errors = _fetch_multi([
        ("tested", HTS_TST_ENTRY_POINTS),
        ("positive", _hts_positive_periods),
        ("linked_w", HTS_LINKED_WITHIN),
        ("linked_o", HTS_LINKED_OUTSIDE),
        ("tx_new", TX_NEW),
    ], ou_id, pe)

    # 2) Modality-level data — ONE analytics call with the full `co` breakdown
    #    so the per-alias rows can be composed exactly like the PBIX SWITCH
    #    measures (HTS_Testing_General / HTS_Testing_Positives).  The old
    #    per-label MODALITY_LABELS fetch could not see a modality element's
    #    HIV+ slice at all.
    rows = _fetch_de_coc_rows(MODALITY_ALL_UIDS, ou_id, pe)
    names = _coc_names_for(MODALITY_ALL_UIDS)
    hivpos = set(HIV_POSITIVE_COCS or [])

    def _is_pos(coc_id, coc_name):
        if hivpos:
            return coc_id in hivpos
        return "HIV+" in (coc_name or "")

    gen = {}     # (uid, period) -> value
    pos = {}     # (uid, period) -> HIV+ only
    coc_periods = set()
    for de, per, coc, val in rows:
        coc_periods.add(per)
        gen[(de, per)] = gen.get((de, per), 0.0) + val
        if _is_pos(coc, names.get(coc, "")):
            pos[(de, per)] = pos.get((de, per), 0.0) + val

    # 3) Test kits — `Test Kits Distributed` = Unassisted + Directly Assisted.
    #    Fetched with the full COC breakdown (named match) for the same reason
    #    as above.
    kits_results, kits_errors = _fetch_named_multi([
        ("assisted", HIV_ST_KITS_ASSISTED, {}),
        ("unassisted", HIV_ST_KITS_UNASSISTED, {}),
    ], ou_id, pe)
    errors.extend(f"kits_{e}" for e in kits_errors)

    # Build trend
    all_periods = sorted(
        set().union(*[d.keys() for d in results.values()], coc_periods),
        key=_period_sort_key,
    )

    trend = []
    for p in all_periods:
        tested = float(results.get("tested", {}).get(p, 0))
        positive = float(results.get("positive", {}).get(p, 0))
        lw = float(results.get("linked_w", {}).get(p, 0))
        lo = float(results.get("linked_o", {}).get(p, 0))
        tx_new_v = float(results.get("tx_new", {}).get(p, 0))

        trend.append({
            "period": p,
            "label": _period_label(p),
            "tested": round(tested, 1),
            "positive": round(positive, 1),
            "linked_within": round(lw, 1),
            "linked_outside": round(lo, 1),
            "total_linked": round(lw + lo, 1),
            "positivity_pct": round(
                (positive / tested * 100) if tested > 0 else 0, 1
            ),
            # 🔥 PBIX `Linkage` (line 469) is literally
            # `DIVIDE([TX_NEW],[HTS Positive], 0)` — a ratio, NOT
            # linked/positive.  The old linked/positive cut invented a 55.8%
            # that appears nowhere in the report.
            "linkage_pct": round(
                min(tx_new_v / positive * 100, 100.0) if positive > 0 else 0, 1
            ),
            "tx_new": round(tx_new_v, 1),
            "pbix_linkage_pct": round(
                (tx_new_v / positive) if positive > 0 else 0, 3
            ),
            "linked_pct": round(
                min((lw + lo) / positive * 100, 100.0) if positive > 0 else 0, 1
            ),
            "tx_new_pct": round(
                min(tx_new_v / positive * 100, 100.0) if positive > 0 else 0, 1
            ),
        })

    # Build modality trend — same composition as /api/testing-modality, but the
    # legacy per-label keys are kept so the existing page JS keeps working.
    modality_trend = []
    modality_all_periods = all_periods
    for p in modality_all_periods:
        entry = {"period": p, "label": _period_label(p)}
        for alias, label, uids, sub in MODALITY_AXIS:
            if uids is None:            # Overall == the master measures
                g = float(results.get("tested", {}).get(p, 0))
                q = float(results.get("positive", {}).get(p, 0))
            else:
                g = sum(gen.get((u, p), 0.0) for u in uids)
                q = sum(pos.get((u, p), 0.0) for u in uids)
                for s in (sub or []):
                    g -= gen.get((s, p), 0.0)
                    q -= pos.get((s, p), 0.0)
            g = max(g, 0.0)
            q = max(q, 0.0)
            key = alias.lower()
            entry[key + "_general"] = round(g, 1)
            entry[key + "_positive"] = round(q, 1)
            entry[key + "_yield"] = round((q / g * 100) if g > 0 else 0, 1)
            # legacy keys: one flat number per modality label (general only)
            entry[label.lower().replace(" ", "_")] = round(g, 1)
        modality_trend.append(entry)

    modality_latest = []
    last = modality_trend[-1] if modality_trend else {}
    for alias, label, uids, sub in MODALITY_AXIS:
        key = alias.lower()
        modality_latest.append({
            "alias": label,
            "general": last.get(key + "_general", 0),
            "positive": last.get(key + "_positive", 0),
            "yield_pct": last.get(key + "_yield", 0),
        })

    # Build kits trend
    kits_all_periods = sorted(
        set(kits_results.get("assisted", {})) | set(kits_results.get("unassisted", {})),
        key=_period_sort_key,
    )
    kits_trend = []
    for p in kits_all_periods:
        assisted = float(kits_results.get("assisted", {}).get(p, 0))
        unassisted = float(kits_results.get("unassisted", {}).get(p, 0))
        kits_trend.append({
            "period": p,
            "label": _period_label(p),
            "directly_assisted": round(assisted, 1),
            "unassisted": round(unassisted, 1),
            "total_kits": round(assisted + unassisted, 1),
        })

    return jsonify({
        "page": "HTS Performance",
        "county": county,
        "source": "dhis2_live",
        "period_range": pe,
        "trend": trend,
        "modality_trend": modality_trend,
        "modality_latest": modality_latest,
        "kits_trend": kits_trend,
        "measures": {
            "tested": "PBIX `HTS Tested` = 17 Jamii + 28 CHAP Stawisha elements",
            "positive": "PBIX `HTS Positive` = the 15 `HTS_TST (facility) - *` "
                        "elements @ HIV Results = HIV+ , + [SNS Pos], + the 28 "
                        "Stawisha New Positive elements",
            "general": "PBIX `HTS_Testing_General` per-alias element sums "
                       "(Other PITC minus HTS_INDEX Contacts Tested)",
            "positive_modality": "PBIX `HTS_Testing_Positives` — the same "
                                 "aliases cut to HIV Results = HIV+",
            "yield": "PBIX `Modality Yield` = DIVIDE([HTS_Testing_Positives],"
                     " [HTS_Testing_General])",
            "kits": "PBIX `Test Kits Distributed` = Directly Assisted + "
                    "Unassisted",
        },
        "fetched_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "errors": errors or None,
    })


