def _period_sort_key(p):
    s = _pe_code(p)
    if len(s) >= 6:
        return (s[:4], s[4:6])
    return (s, "")


_MONTH_CODES = {n.lower(): i + 1 for i, n in enumerate(
    ("Jan", "Feb", "Mar", "Apr", "May", "Jun",
     "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"))}


def _pe_code(p):
    """Normalise any period representation to the 6-char DHIS2 code.

    `_dhis2_fetch` keys its dicts by **display name** (``"June 2026"``) while
    the raw analytics helpers key by **code** (``"202606"``), so anything that
    does calendar arithmetic has to accept both.
    """
    s = str(p).strip()
    if len(s) == 6 and s.isdigit():
        return s
    parts = s.replace(",", " ").split()
    if len(parts) == 2:
        mon = _MONTH_CODES.get(parts[0].lower()[:3])
        yr = parts[1]
        if mon and len(yr) == 4 and yr.isdigit():
            return "%04d%02d" % (int(yr), mon)
    return s


def _period_label(p):
    s = str(p)
    if len(s) == 6:
        month_names = [
            "Jan", "Feb", "Mar", "Apr", "May", "Jun",
            "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
        ]
        try:
            m = int(s[4:6])
            return f"{month_names[m-1]} {s[:4]}"
        except ValueError:
            return f"{s[:4]}-{s[4:]}"
    return s


_MONTH_FULL = ("January", "February", "March", "April", "May", "June",
               "July", "August", "September", "October", "November",
               "December")


def _pe_name(p):
    """Return the DHIS2 *display* form of a period — ``202606`` -> ``June 2026``.

    Ageing-side twin of `_pe_code`; needed because a single endpoint routinely
    mixes dicts keyed by code with dicts keyed by display name.
    """
    code = _pe_code(p)
    if len(code) == 6 and code.isdigit():
        m = int(code[4:6])
        if 1 <= m <= 12:
            return "%s %s" % (_MONTH_FULL[m - 1], code[:4])
    return str(p)


def _pick(d, period, default=0.0):
    """Read one period out of a ``{period: value}`` dict in EITHER key space.

    🔥 `_dhis2_fetch` (and therefore `_fetch_multi` / `_fetch_named_multi`)
    keys by `metaData.items` **display name** (``"June 2026"``) whereas the
    calendar helpers (`_quarter_months`, `_prior_quarter_end_period`) never
    return anything but 6-char **codes** (``"202603"``).  A bare
    ``d.get(period)`` therefore silently yields 0 — which is how every
    ``%IIT`` denominator in the dashboards came to read zero.
    """
    if not d:
        return float(default)
    for k in (period, _pe_code(period), _pe_name(period),
              _period_label(period)):
        if k in d:
            try:
                return float(d[k] or 0)
            except (TypeError, ValueError):
                return float(default)
    return float(default)


