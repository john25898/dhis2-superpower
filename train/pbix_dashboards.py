_ANALYTICS_SESSION = None


def _analytics_get(params, timeout=180, attempts=3):
    """GET ``analytics.json``, splitting cross-year period sets when needed.

    A thin wrapper over `_analytics_get_once`: this session deliberately
    bypasses `services.dhis2.chak_get`, so the CHAK cross-year workaround
    (which chak_get applies centrally) has to be applied here too — otherwise
    every ``co:``-based measure on this page set stays blank for eleven months
    of the year.  When the period set sits inside one calendar year nothing
    changes: one request, returned verbatim.
    """
    from services.dhis2 import chak_analytics_query

    def _once(query_params):
        body = _analytics_get_once(query_params, timeout, attempts)
        if body is None:
            return False, None, None
        return True, body, None

    body, _raw, _merged = chak_analytics_query(params, _once)
    return body


def _analytics_get_once(params, timeout=180, attempts=3):
    """GET ``analytics.json`` through a retrying, keep-alive-free session.

    The CHAK server intermittently truncates large ``dimension=co`` responses
    (urllib3 raises ``IncompleteRead``); without a retry the exception is
    swallowed by the callers and a whole measure silently reads as zero.
    Returns the parsed JSON body, or ``None`` if every attempt failed.
    """
    import requests as req
    from requests.auth import HTTPBasicAuth
    from requests.adapters import HTTPAdapter

    try:
        from urllib3.util.retry import Retry
    except Exception:  # pragma: no cover
        Retry = None

    global _ANALYTICS_SESSION
    if _ANALYTICS_SESSION is None:
        s = req.Session()
        if Retry is not None:
            adapter = HTTPAdapter(max_retries=Retry(
                total=attempts, connect=attempts, read=attempts,
                backoff_factor=1.0,
                status_forcelist=(429, 500, 502, 503, 504),
                allowed_methods=frozenset(["GET"])))
        else:  # pragma: no cover
            adapter = HTTPAdapter(max_retries=attempts)
        s.mount("http://", adapter)
        s.mount("https://", adapter)
        s.auth = HTTPBasicAuth(os.getenv("DHIS_USERNAME") or "Johnbrian",
                               os.getenv("DHIS_PASSWORD") or "JOHNb123\\")
        s.headers.update({"Connection": "close"})
        _ANALYTICS_SESSION = s

    base = os.getenv("DHIS_BASE_URL") or "https://ereporting.chak.or.ke/api/"
    url = base.rstrip("/") + "/analytics.json"
    for _ in range(max(1, attempts)):
        try:
            r = _ANALYTICS_SESSION.get(url, params=params, timeout=timeout)
            if r.ok:
                return r.json() or {}
        except Exception:
            continue
    return None


def _pe_label(data, code):
    """Map a raw DHIS2 period code to the display label used everywhere else.

    `_dhis2_fetch` returns ``{"June 2026": value}`` (it resolves the codes via
    the response's ``metaData.items``).  The COC helpers talk to
    ``analytics.json`` directly and would otherwise key by ``"202606"``, so any
    endpoint that mixes both silently reads **zero** for every COC-sliced row.
    """
    try:
        item = (data.get("metaData", {}) or {}).get("items", {}) or {}
        hit = item.get(str(code))
        if hit and hit.get("name"):
            return str(hit["name"])
    except Exception:
        pass
    return str(code)


def _fetch_coc_named(de_ids, ou_id, pe="LAST_12_MONTHS",
                     prefixes=None, contains=None, exclude_contains=None,
                     cocs_keep=None, cocs_drop=None):
    """Fetch element(s) with their FULL COC breakdown and sum only the COCs
    whose **name** matches, plus optional COC-id keep/drop sets.

    This exists because CHAK DHIS2 silently ignores a ``co:<uid>`` filter when
    the uids belong to a category combo other than the element's own — the
    request then returns the unfiltered total.  Name matching on the full
    breakdown (the approach `blueprints/milestone.py` already uses) is the only
    reliable way to slice e.g. "C&T (facility) - Tx_ML, Outcomes" by outcome.

    Args:
        prefixes:         list of COC-name prefixes to INCLUDE (any match).
        contains:         list of substrings to INCLUDE (any match).
        exclude_contains: list of substrings to EXCLUDE (any match).
        cocs_keep:        explicit COC ids to keep (post-name filter).
        cocs_drop:        explicit COC ids to drop.
    Returns ``{period: value}``.
    """
    ids = [de_ids] if isinstance(de_ids, str) else list(de_ids or [])
    if not ids:
        return {}
    # ou_id may be a set/list — join with ";" (the separator DHIS2 expects).
    if isinstance(ou_id, (list, tuple, set)):
        ou_str = ";".join(str(x) for x in ou_id)
    else:
        ou_str = str(ou_id)
    params = [
        ("dimension", "dx:" + ";".join(ids)),
        ("dimension", "pe:" + _normalize_pe(pe)),
        ("dimension", "ou:" + ou_str),
        ("dimension", "co"),
        ("displayProperty", "NAME"),
    ]
    data = _analytics_get(params, timeout=180)
    if not data:
        return {}
    hdrs = [h.get("name", "").lower() for h in data.get("headers", [])]
    if "co" not in hdrs:
        return {}
    co_i = hdrs.index("co")
    pe_i = hdrs.index("pe") if "pe" in hdrs else 0
    v_i = hdrs.index("value") if "value" in hdrs else len(hdrs) - 1
    dx_i = hdrs.index("dx") if "dx" in hdrs else None

    names = {}
    for i in ids:
        names.update(_coc_names_for_element(i))

    keep = set(cocs_keep) if cocs_keep else None
    drop = set(cocs_drop) if cocs_drop else set()
    out: dict = {}
    for row in data.get("rows", []):
        raw_co = str(row[co_i])
        nm = names.get(raw_co, "")
        if keep is not None and raw_co not in keep:
            continue
        if raw_co in drop:
            continue
        if prefixes or contains or exclude_contains:
            ok = False
            if prefixes and any(nm.startswith(p) for p in prefixes):
                ok = True
            if contains and any(c in nm for c in contains):
                ok = True
            if not ok:
                continue
            if exclude_contains and any(c in nm for c in exclude_contains):
                continue
        try:
            val = float(row[v_i] or 0)
        except (TypeError, ValueError):
            val = 0.0
        per = _pe_label(data, row[pe_i])
        out[per] = out.get(per, 0.0) + val
    return out


def _fetch_de_coc_rows(ids, ou_id, pe="LAST_12_MONTHS", chunk=5):
    """Return raw (de_id, period, coc_id, value) rows for `ids`, each with its
    FULL ``dimension=co`` breakdown.

    Needed because several PBIX measures are a SUM of ONE element sliced by a
    *dimension COC label* (e.g. `Total IIT`, `TX_ML`, `MMD Children`, every
    `HTS_Testing_Positives` modality), and because DHIS2's ``co:<uid>`` filter
    silently returns the unfiltered total when the uids belong to another
    category combo.

    ``ids`` is requested in chunks (the 17-element modality call otherwise
    returns a ~2 MB body that the CHAK server truncates) and merged, so the
    caller still sees one flat row list.
    """
    if isinstance(ids, str):
        ids = [x for x in ids.split(";") if x]
    ids = [x for x in ids if x]
    if not ids:
        return []
    # DHIS2 wants the ou dimension joined with ";" (see services/dhis2.py); a
    # wrong separator makes analytics.json return zero rows with HTTP 200.
    if isinstance(ou_id, (list, tuple, set)):
        ou_str = ";".join(str(x) for x in ou_id)
    else:
        ou_str = str(ou_id)
    try:
        step = max(1, int(chunk))
    except (TypeError, ValueError):
        step = 5

    out = []
    for i in range(0, len(ids), step):
        part = ids[i:i + step]
        params = [("dimension", "dx:" + ";".join(part)),
                  ("dimension", "pe:" + _normalize_pe(pe)),
                  ("dimension", "ou:" + ou_str),
                  ("dimension", "co"),
                  ("displayProperty", "NAME")]
        data = _analytics_get(params, timeout=180)
        if not data:
            continue
        hdrs = [h.get("name", "").lower() for h in data.get("headers", [])]
        idx = {h: j for j, h in enumerate(hdrs)}
        if not all(k in idx for k in ("dx", "pe", "co", "value")):
            return []
        for row in data.get("rows", []):
            try:
                val = float(row[idx["value"]] or 0)
            except (TypeError, ValueError):
                val = 0.0
            out.append((str(row[idx["dx"]]), _pe_label(data, row[idx["pe"]]),
                        str(row[idx["co"]]), val))
    return out


def _coc_names_for(ids):
    """Union of {coc_id: name} for the given data elements."""
    names = {}
    for i in (ids.split(";") if isinstance(ids, str) else ids):
        if i:
            names.update(_coc_names_for_element(i))
    return names


def _fetch_named_multi(specs, ou_id, pe="LAST_12_MONTHS"):
    results, errors = {}, []
    with ThreadPoolExecutor(max_workers=6) as ex:
        futs = {}
        for spec in specs:
            key, de_id = spec[0], spec[1]
            kw = spec[2] if len(spec) > 2 else {}
            futs[ex.submit(_fetch_coc_named, de_id, ou_id, pe, **kw)] = key
        for fut in as_completed(futs):
            key = futs[fut]
            try:
                results[key] = fut.result() or {}
            except Exception as exc:  # pragma: no cover
                errors.append("%s: %s" % (key, exc))
                results[key] = {}
    return results, errors


def _prior_quarter_end_period(p):
    """PBIX `%IIT` / `%IIT_Quarterly` baseline month.

    Months 1-3 -> Dec of the previous year, 4-6 -> Mar, 7-9 -> Jun, 10-12 -> Sep.
    """
    s = _pe_code(p)
    if len(s) != 6:
        return None
    y, m = int(s[:4]), int(s[4:6])
    if m in (1, 2, 3):
        return "%04d12" % (y - 1)
    if m in (4, 5, 6):
        return "%04d03" % y
    if m in (7, 8, 9):
        return "%04d06" % y
    return "%04d09" % y


def _quarter_start_period(p):
    """First month of the PBIX calendar quarter containing ``p``."""
    s = _pe_code(p)
    if len(s) != 6:
        return None
    y, m = int(s[:4]), int(s[4:6])
    qs = 10 if m >= 10 else (7 if m >= 7 else (4 if m >= 4 else 1))
    return "%04d%02d" % (y, qs)


def _quarter_months(p):
    """The three period codes of the quarter containing ``p``."""
    qs = _quarter_start_period(p)
    if not qs:
        return []
    y, m = int(qs[:4]), int(qs[4:6])
    out = []
    for k in range(3):
        mm = m + k
        yy = y
        if mm > 12:
            mm -= 12
            yy += 1
        out.append("%04d%02d" % (yy, mm))
    return out


def _quarter_months_to_date(p):
    """`_quarter_months(p)` truncated at ``p``.

    🔥 PBIX `%IIT` computes NM1..NM3 but only sums the ones already elapsed
    (``MonthsIntoQtr = CurrentMonth - QtrStartMonth + 1``), whereas
    `%IIT_Quarterly` always sums all three months of the quarter.
    """
    months = _quarter_months(p)
    code = _pe_code(p)
    if len(code) != 6 or not code.isdigit():
        return months
    out = [m for m in months if m <= code]
    return out or months


def _pe_bounds(pe):
    """(min_code, max_code) of the 6-char month codes inside a ``pe`` string.

    Returns ``(None, None)`` for a relative window such as ``LAST_12_MONTHS``
    — i.e. when the caller never named an explicit month.
    """
    codes = []
    for part in str(pe or "").split(";"):
        code = _pe_code(part)
        if len(code) == 6 and code.isdigit():
            codes.append(code)
    if not codes:
        return None, None
    return min(codes), max(codes)


def _widen_pe(pe, back=6):
    """Widen an explicit ``pe`` backwards so PBIX *baseline* lookups resolve.

    🔥 PBIX `TX_CURR_Previous_Quarter` is
    ``CALCULATE(SUM(...), PREVIOUSQUARTER('Date'[Date]))`` — it reads the date
    table, NOT the period slicer.  Asking DHIS2 for a single month therefore
    returns that month only, leaving both the prior-quarter TX_CURR baseline
    and the 3-month TX_NEW cohort out of the response, which is exactly how
    `%IIT` came to read 245% instead of 1.1%.
    """
    lo, hi = _pe_bounds(pe)
    if hi is None:
        return pe                      # relative window is already wide enough
    y, m = int(hi[:4]), int(hi[4:6])
    codes = []
    for i in range(back, -1, -1):
        mm, yy = m - i, y
        while mm <= 0:
            mm += 12
            yy -= 1
        codes.append("%04d%02d" % (yy, mm))
    # Keep anything the caller asked for that falls BEFORE the widened start.
    if lo is not None and lo < codes[0]:
        for part in str(pe).split(";"):
            code = _pe_code(part)
            if len(code) == 6 and code.isdigit() and code < codes[0]:
                codes.insert(0, code)
    return ";".join(dict.fromkeys(codes))


def _in_pe_window(p, lo, hi):
    """True when ``p`` sits inside an explicitly-requested ``pe`` window."""
    if lo is None:
        return True
    code = _pe_code(p)
    return len(code) == 6 and code.isdigit() and lo <= code <= hi


